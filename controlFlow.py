val = input("Enter the number: ")

# if
if(float(val)%2 == 0):
  print("The number is even")
else: 
  print("The number is odd")

# if-else
newVal = float(input("Enter the number: "))
if(newVal > 89):
  print("The number is greater than 90")
else:
  print("The number is less than 90")

